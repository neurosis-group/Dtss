function openCity(evt, cityName) {

    // Hide all tab contents
    var tabcontent = document.getElementsByClassName("com-tabcontent");
    for (var i = 0; i < tabcontent.length; i++) {
        tabcontent[i].style.display = "none";
    }

    // Remove active class
    var tablinks = document.getElementsByClassName("tablinks");
    for (var i = 0; i < tablinks.length; i++) {
        tablinks[i].classList.remove("active");
    }

    // Show selected tab
    document.getElementById(cityName).style.display = "block";

    if (evt) {
        evt.currentTarget.classList.add("active");
    }

    // Update URL without reload
    history.replaceState(null, null, "#" + cityName);
}

// On Page Load
window.addEventListener("load", function () {

    let hash = window.location.hash.replace("#", "");

    if (hash && document.getElementById(hash)) {

        document.getElementById(hash).style.display = "block";

        let buttons = document.querySelectorAll(".tablinks");

        buttons.forEach(function(btn){

            if(btn.getAttribute("onclick").includes("'" + hash + "'")){
                btn.classList.add("active");
            }

        });

    } else {

        // Default Tab
        openCity(null, "CorporateSocialResponsibility");

        let firstBtn = document.querySelector(".tablinks");
        if(firstBtn){
            firstBtn.classList.add("active");
        }
    }
});
